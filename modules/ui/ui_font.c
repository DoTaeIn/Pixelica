static bool builtin_glyph(void *userdata, uint32_t codepoint, uint32_t rows[32])
{
    const uint8_t *src;
    uint32_t r;

    (void)userdata;
    if (codepoint >= (uint32_t)'a' && codepoint <= (uint32_t)'z') {
        codepoint -= 32u;
    }
    if (codepoint < FONT_FIRST || codepoint > FONT_LAST) {
        codepoint = (uint32_t)'?';
    }
    src = &k_rows[(codepoint - FONT_FIRST) * FONT_ROWS];
    for (r = 0; r < FONT_ROWS; ++r) {
        rows[r] = (uint32_t)src[r] << 24;
    }
    return true;
}

PIXELICA_UI_Font pixelica_ui_font_default(void)
{
    PIXELICA_UI_Font font;

    font.width = 5u;
    font.height = 7u;
    font.scale = 1u;
    font.glyph = builtin_glyph;
    font.userdata = NULL;
    return font;
}
