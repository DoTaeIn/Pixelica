/*
 * Pixelica UI - built-in 5x7 font.
 * See modules/ui/include/pixelica/ui.h.
 *
 * The bitmap data is the classic 5x7 table of examples/common2d/demo_art.h
 * (ASCII 32..90, upper case), copied here so the module has no example
 * dependency. Lower case maps to upper case; every other code point, including
 * all non-ASCII Unicode, draws '?'. There is no built-in Korean/CJK font: use a
 * custom PIXELICA_UI_GlyphFn for that.
 */
#include <stdint.h>

#include "pixelica/ui.h"

#define FONT_FIRST 32u
#define FONT_LAST 90u
#define FONT_ROWS 7u

/* Five bits per row, stored left-aligned in a byte (bit 7 = left pixel). */
