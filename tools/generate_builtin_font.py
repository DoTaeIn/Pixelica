#!/usr/bin/env python3
"""Regenerate the bundled GalmuriMono11 table from its pinned upstream BDF.
OFL-1.1 applies to the generated bitmap data. No network, stdlib only.
Upstream CHARS excludes its final ENCODING -1 .notdef; repair only this known
pinned source in memory. General BDF parsing remains strict.
"""
from pathlib import Path
import hashlib
import re
from pixelica_font import parse_bdf, _cell_rows

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'assets/fonts/galmuri/GalmuriMono11.bdf'

def generate():
    raw = SOURCE.read_bytes()
    expected = (SOURCE.parent / 'SHA256SUMS.txt').read_text().split()[0]
    if hashlib.sha256(raw).hexdigest() != expected:
        raise ValueError('Pinned BDF checksum mismatch')
    text = raw.decode('utf-8')
    count = len(re.findall(r'^STARTCHAR ', text, re.M))
    declared = int(re.search(r'^CHARS (\d+)$', text, re.M)[1])
    if count != declared + 1 or text.count('ENCODING -1\n') != 1:
        raise ValueError('Unexpected upstream glyph count')
    text = re.sub(r'^CHARS \d+$', 'CHARS ' + str(count), text, flags=re.M)
    font = parse_bdf(text.encode())
    codes = sorted(font.glyphs)
    out = ['/* Generated by tools/generate_builtin_font.py. OFL-1.1 bitmap data.',
           ' * Copyright (c) 2019–2025 Lee Minseo (quiple@quiple.dev).',
           ' * See assets/fonts/galmuri/OFL.txt. Do not edit. */',
           'static const uint32_t korean_codes[] = {']
    for i in range(0, len(codes), 12):
        out.append('    ' + ', '.join('0x%Xu' % c for c in codes[i:i+12]) + ',')
    out.append('};\nstatic const uint16_t korean_rows[][16] = {')
    for cp in codes:
        rows = _cell_rows(font, font.glyphs[cp], cp, 16, 16, 14, -4)
        out.append('    {' + ','.join('0x%04X' % (r >> 16) for r in rows) + '},')
    out.append('};\n')
    return '\n'.join(out)

if __name__ == '__main__':
    (ROOT / 'src/game/font_korean_data.inc').write_text(generate(), encoding='utf-8')
