#!/usr/bin/env python3
"""Regenerate the Pixel Room demo assets reproducibly (stdlib only).

    python tools/pixelica_pack/generate_demo_assets.py [--output-root DIR] [--check]

Writes, below the output root (default: the repository root):
    assets/source/vox/{desk,chair,book,cup,plant}.vox   procedural VOX sources
    assets/source/textures/checker.ppm                  procedural floor texture
    assets/compiled/{desk,chair,book,cup,plant}.p3mesh  via the real importer
    assets/compiled/checker.p3tex                       via the real PPM path
    assets/compiled/room.p3cart                         via the real bundler
    assets/compiled/pixel_room_assets.h                 C byte arrays

The compiled files are produced by exactly the code the pixelica_pack CLI runs
(vox.import_vox, ppm.ppm_to_p3tex, pixelica_format.bundle_named); this script has no
meshing or packing logic of its own. Output is byte-for-byte deterministic.

--check regenerates in memory and compares with the files on disk (exit 1 on
any difference) without writing anything.
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import demo_models  # noqa: E402
import pixelica_format  # noqa: E402
import ppm  # noqa: E402
import vox  # noqa: E402
from pixelica_format import PixelicaPackError  # noqa: E402

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

HEADER_PATH = "assets/compiled/pixel_room_assets.h"
CART_PATH = "assets/compiled/room.p3cart"
CART_RESOURCES = ("book", "chair", "checker", "cup", "desk", "plant")

CHECKER_SIZE = 32
CHECKER_TILE = 8
CHECKER_LIGHT = (206, 176, 128)
CHECKER_DARK = (160, 124, 88)
CHECKER_GROUT = (118, 88, 62)


def make_checker_ppm():
    rows = []
    for y in range(CHECKER_SIZE):
        row = bytearray()
        for x in range(CHECKER_SIZE):
            if x % CHECKER_TILE == 0 or y % CHECKER_TILE == 0:
                rgb = CHECKER_GROUT
            elif ((x // CHECKER_TILE) + (y // CHECKER_TILE)) % 2 == 0:
                rgb = CHECKER_LIGHT
            else:
                rgb = CHECKER_DARK
            row += bytes(rgb)
        rows.append(bytes(row))
    head = ("P6\n%d %d\n255\n" % (CHECKER_SIZE, CHECKER_SIZE)).encode("ascii")
    return head + b"".join(rows)


def c_array(symbol, data):
    lines = ["static const uint8_t %s[] = {" % symbol]
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        lines.append("    " + ", ".join("0x%02x" % b for b in chunk) + ",")
    lines.append("};")
    lines.append("static const size_t %s_size = sizeof %s;" % (symbol, symbol))
    return "\n".join(lines)


def make_header(blobs, cart):
    """blobs: ordered (symbol, bytes); cart: decoded CartEntry list."""
    parts = [
        "/* Generated by tools/pixelica_pack/generate_demo_assets.py - do not edit.",
        " *",
        " * Embedded Pixel Room assets so the demo needs no runtime filesystem",
        " * access. Each *_size is the byte length of the matching array.",
        " * Resource ids inside pixelica_asset_room_cart follow ascending name order.",
        " */",
        "#ifndef PIXELICA_PIXEL_ROOM_ASSETS_H",
        "#define PIXELICA_PIXEL_ROOM_ASSETS_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
    ]
    for entry in cart:
        parts.append("#define PIXELICA_ROOM_CART_ID_%s %du"
                     % (entry.name.upper(), entry.resource_id))
    parts.append("")
    for symbol, data in blobs:
        parts.append(c_array(symbol, data))
        parts.append("")
    parts.append("#endif /* PIXELICA_PIXEL_ROOM_ASSETS_H */")
    return ("\n".join(parts) + "\n").encode("ascii")


def build_outputs():
    """Return an ordered list of (relative posix path, bytes)."""
    out = []
    compiled = {}
    for name, builder in demo_models.PROPS:
        source = builder().to_vox()
        out.append(("assets/source/vox/%s.vox" % name, source))
        mesh = vox.vox_to_p3mesh(source)
        compiled[name] = mesh
    checker_ppm = make_checker_ppm()
    out.append(("assets/source/textures/checker.ppm", checker_ppm))
    compiled["checker"] = ppm.ppm_to_p3tex(checker_ppm)

    for name, _builder in demo_models.PROPS:
        out.append(("assets/compiled/%s.p3mesh" % name, compiled[name]))
    out.append(("assets/compiled/checker.p3tex", compiled["checker"]))

    cart = pixelica_format.bundle_named([(n, compiled[n]) for n in CART_RESOURCES])
    out.append((CART_PATH, cart))

    blobs = [("pixelica_asset_%s" % n, compiled[n])
             for n in ("desk", "chair", "book", "cup", "plant", "checker")]
    blobs.append(("pixelica_asset_room_cart", cart))
    out.append((HEADER_PATH, make_header(blobs, pixelica_format.decode_cart(cart))))
    return out


def write_outputs(root, outputs):
    for rel, data in outputs:
        path = os.path.join(root, *rel.split("/"))
        os.makedirs(os.path.dirname(path), exist_ok=True)
        pixelica_format.atomic_write(path, data)


def check_outputs(root, outputs):
    problems = []
    for rel, data in outputs:
        path = os.path.join(root, *rel.split("/"))
        if not os.path.isfile(path):
            problems.append("missing: %s" % rel)
            continue
        with open(path, "rb") as handle:
            if handle.read() != data:
                problems.append("differs: %s" % rel)
    return problems


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--output-root", default=REPO_ROOT,
                        help="directory that receives assets/ (default: repo root)")
    parser.add_argument("--check", action="store_true",
                        help="compare with files on disk instead of writing")
    args = parser.parse_args(argv)
    try:
        outputs = build_outputs()
        if args.check:
            problems = check_outputs(args.output_root, outputs)
            for line in problems:
                print(line)
            print("assets up to date" if not problems
                  else "%d file(s) out of date" % len(problems))
            return 1 if problems else 0
        write_outputs(args.output_root, outputs)
    except (PixelicaPackError, OSError) as exc:
        print("generate_demo_assets: error: %s" % exc, file=sys.stderr)
        return 1
    for rel, data in outputs:
        print("%-44s %7d bytes" % (rel, len(data)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
